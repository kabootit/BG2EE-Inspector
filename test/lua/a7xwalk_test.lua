-- The walker (mod/inspector/lib/a7xwalk.lua) against a fake game in a Lua table of bytes: a party of
-- two, one on each stats block, a custom name and a strref name, an empty weapon slot, improved
-- invisibility, the area on screen, the creatures in it and the one under the pointer, EA groups, and
-- the hostile cases (bad counts, stale ids, wrong types, unreadable pointers and blocks, a bad area
-- index).

local T = dofile("test/lua/testlib.lua")
local F = dofile("test/lua/fakegame.lua") -- loads a7xoff.lua, which the walker reads at load
dofile("mod/inspector/lib/a7xwalk.lua")
local O = A7XOFF
local ROOT, GAME, ARRAY, A, B, ID_A, ID_B = F.ROOT, F.GAME, F.ARRAY, F.A, F.B, F.ID_A, F.ID_B
local field, world = F.field, F.world

T.test("the party is found in slot order through the object array", function()
  world()
  local party = assert(A7XWALK.party())
  T.eq(#party, 2, "party size")
  T.eq(party[1].id, ID_A, "first id")
  T.eq(party[1].sprite, A, "first sprite")
  T.eq(party[2].sprite, B, "second sprite")
end)

T.test("a creature on the derived block, with a custom name and a weapon", function()
  world()
  local c = assert(A7XWALK.creature(A))
  T.eq(c.name, "Alarion", "name")
  T.eq(c.resref, "ALARION", "resref, cut at the first NUL")
  T.eq(c.stats_block, "derived", "block")
  T.eq(c.hp.cur, 40, "hp")
  T.eq(c.hp.max, 52, "max hp")
  T.eq(c.ac.value, -2, "ac")
  T.eq(c.ac.missile, 1, "missile ac")
  T.eq(c.thac0, 9, "thac0")
  T.eq(c.thac0_shown, 9 - 2 - 1, "thac0 shown")
  T.eq(c.saves.death, 4, "death save")
  T.eq(c.saves_base.spell, 14, "base spell save")
  T.eq(c.saves_shown.spell, 7, "shown spell save")
  T.eq(c.resist.fire, 25, "fire resistance")
  T.eq(c.mr, 10, "magic resistance")
  T.eq(c.ea, 2, "ea")
end)

T.test("a creature on the temp block, with a strref name, no weapon, improved invisibility", function()
  world()
  local c = assert(A7XWALK.creature(B))
  T.eq(c.name, "Jaheira", "name")
  T.eq(c.resref, "", "an empty resref")
  T.eq(c.stats_block, "temp", "block")
  T.eq(c.hp.max, 30, "max hp from temp")
  T.eq(c.saves.death, 6, "death save from temp")
  T.eq(c.thac0_shown, 0, "thac0 shown with an empty weapon slot")
  T.eq(c.saves_shown.death, 8 - 4, "shown save: derived, 4 better under improved invisibility")
end)

T.test("a party count out of range is refused", function()
  world()
  field(GAME, O.game.party_count, 99)
  local party, why = A7XWALK.party()
  T.eq(party, nil, "party")
  T.eq(why, "bad party count", "reason")
end)

T.test("a stale, foreign or out-of-range id finds nothing", function()
  world()
  T.eq(select(2, A7XWALK.lookup(5 * 65536 + 1999)), "stale id", "stale")
  T.eq(select(2, A7XWALK.lookup(7 * 65536 + 2001)), "stale id", "empty slot's generation")
  T.eq(select(2, A7XWALK.lookup(50 * 65536)), "id outside the array", "past highest")
  T.eq(select(2, A7XWALK.lookup(-1)), "bad id", "negative")
  field(ARRAY, O.objects.highest, 200)
  T.eq(select(2, A7XWALK.lookup(150 * 65536)), "id outside the array", "past capacity")
end)

T.test("a wrong type byte, a null or -1 pointer, and no game are refused", function()
  world()
  field(A, O.object.type, 0x10)
  T.eq(select(2, A7XWALK.creature(A)), "not a sprite", "type")
  T.eq(select(2, A7XWALK.creature(0)), "bad sprite pointer", "null")
  T.eq(select(2, A7XWALK.creature(2 ^ 64 - 1)), "bad sprite pointer", "-1 as unsigned")
  T.eq(select(2, A7XWALK.creature(0x900000)), "not a sprite", "unmapped")
  field(ROOT, O.chitin.game, 0)
  T.eq(select(2, A7XWALK.party()), "no game loaded", "no game")
end)

T.test("the visible area is the indexed entry of the area table, with its resref", function()
  world()
  local v = assert(A7XWALK.visible_area())
  T.eq(v.index, 0, "index")
  T.eq(v.pointer, F.AREA1, "pointer")
  T.eq(v.resref, "AR0602", "resref, cut at the first NUL")
  field(GAME, O.game.visible_area, 1)
  T.eq(A7XWALK.visible_area().resref, "AR0603", "the other area")
end)

T.test("a bad visible area index, an empty entry and no game are refused", function()
  world()
  field(GAME, O.game.visible_area, O.game.area_count)
  T.eq(select(2, A7XWALK.visible_area()), "bad visible area index", "index past the table")
  field(GAME, O.game.visible_area, 2)
  T.eq(select(2, A7XWALK.visible_area()), "no visible area", "empty entry")
  field(ROOT, O.chitin.game, 0)
  T.eq(select(2, A7XWALK.visible_area()), "no game loaded", "no game")
end)

T.test("the creatures in an area are its sprites only, across 256-slot blocks", function()
  world()
  F.crowd()
  local list, counts = assert(A7XWALK.creatures(F.AREA1))
  T.eq(#list, 3, "A, B and C")
  T.eq(list[1].id, ID_A, "first in slot order")
  T.eq(list[2].sprite, B, "second")
  T.eq(list[3].id, F.ID_C, "C, from the second block")
  T.eq(list[3].ea, 255, "C's EA")
  T.eq(counts.slots, 301, "slots scanned: highest + 1")
  T.eq(counts.objects, 5, "live objects: A, B, C, D, E")
  T.eq(counts.sprites, 4, "sprites: E is not one")
  local other = assert(A7XWALK.creatures(F.AREA2))
  T.eq(#other, 1, "the other area")
  T.eq(other[1].id, F.ID_D, "D")
end)

T.test("a scan stops at the array's capacity, and an unreadable block or bad area is refused", function()
  world()
  F.crowd()
  field(ARRAY, O.objects.capacity, 200)
  local list, counts = assert(A7XWALK.creatures(F.AREA1))
  T.eq(counts.slots, 200, "capacity, not highest + 1")
  T.eq(#list, 2, "C, at slot 300, is past it")
  field(ARRAY, O.objects.capacity, 400)
  F.fail_blocks[ARRAY + 256 * 16] = true
  T.eq(select(2, A7XWALK.creatures(F.AREA1)), "object array unreadable at slot 256", "second block")
  T.eq(select(2, A7XWALK.creatures(0)), "bad area pointer", "null area")
end)

T.test("the creature under the pointer is the sprite whose id the area on screen holds", function()
  world()
  F.crowd()
  field(F.AREA1, O.area.picked, F.ID_C)
  T.eq(A7XWALK.picked(), F.C, "C, from the second block")
  field(F.AREA1, O.area.picked, ID_B)
  T.eq(A7XWALK.picked(), B, "a party member")
  field(F.AREA2, O.area.picked, F.ID_D)
  T.eq(A7XWALK.picked(), B, "the other area's field is not read")
end)

T.test("nothing, a stale id, an object that is no creature and no area are refused", function()
  world()
  F.crowd()
  T.eq(select(2, A7XWALK.picked()), "nothing under the pointer", "id -1")
  field(F.AREA1, O.area.picked, ID_A + 1)
  T.eq(select(2, A7XWALK.picked()), "stale id", "a generation the slot no longer has")
  field(F.AREA1, O.area.picked, F.ID_E)
  T.eq(select(2, A7XWALK.picked()), "not a creature", "E, a door or container")
  field(GAME, O.game.visible_area, 2)
  T.eq(select(2, A7XWALK.picked()), "no visible area", "no area on screen")
end)

T.test("EA groups follow the engine's cut-offs at 30 and 200", function()
  T.eq(A7XWALK.ea_group(2), "friendly", "PC")
  T.eq(A7XWALK.ea_group(30), "friendly", "GOODCUTOFF")
  T.eq(A7XWALK.ea_group(31), "neutral", "past GOODCUTOFF")
  T.eq(A7XWALK.ea_group(199), "neutral", "below EVILCUTOFF")
  T.eq(A7XWALK.ea_group(200), "hostile", "EVILCUTOFF")
  T.eq(A7XWALK.ea_group(nil), nil, "no EA")
end)

T.test("a sprite's effect lists, each effect's fields in list order", function()
  world()
  F.effects(A, "timed", {
    { opcode = 142, p2 = 38, timing = 4096, duration = 12369494, source = "SPPR101" },
    { opcode = 0, timing = 4096, duration = 12369494, source = "SPPR101" },
  })
  F.effects(A, "equipped", { { opcode = 1, timing = 2, source = "RING02" } })
  local timed = assert(A7XWALK.effects(A, "timed"))
  T.eq(#timed, 2, "two timed effects")
  local e = timed[1]
  T.eq(table.concat({ e.opcode, e.p2, e.timing, e.duration, e.applied, e.source }, " "),
    "142 38 4096 12369494 900 SPPR101", "the first, every field")
  T.eq(timed[2].opcode, 0, "the second, in list order")
  local equipped = assert(A7XWALK.effects(A, "equipped"))
  T.eq(#equipped .. " " .. equipped[1].source .. " " .. equipped[1].timing, "1 RING02 2", "equipped")
  T.eq(#assert(A7XWALK.effects(B, "timed")), 0, "an empty list is an empty table")
end)

T.test("a broken, endless or unknown effect list, or no sprite, gives a reason", function()
  world()
  F.effects(A, "timed", { { opcode = 0 } })
  field(A, O.sprite.timed_effects, 0x10)
  T.eq(select(2, A7XWALK.effects(A, "timed")), "bad node pointer", "a node pointing nowhere")
  local many = {}
  for i = 1, O.effect_node.max + 1 do many[i] = { opcode = 0 } end
  F.effects(A, "timed", many)
  T.eq(select(2, A7XWALK.effects(A, "timed")), "more than 256 effects", "past the cap")
  T.eq(select(2, A7XWALK.effects(A, "worn")), "no such list: worn", "an unknown list")
  T.eq(select(2, A7XWALK.effects(0, "timed")), "bad sprite pointer", "no sprite")
end)

T.test("without A7X_native every function says so", function()
  local saved = A7X_native
  A7X_native = nil
  T.eq(select(2, A7XWALK.party()), "no A7X_native", "party")
  T.eq(select(2, A7XWALK.lookup(ID_A)), "no A7X_native", "lookup")
  T.eq(select(2, A7XWALK.visible_area()), "no A7X_native", "visible area")
  T.eq(select(2, A7XWALK.creatures(F.AREA1)), "no A7X_native", "creatures")
  T.eq(select(2, A7XWALK.picked()), "no A7X_native", "picked")
  A7X_native = saved
end)

T.done()
