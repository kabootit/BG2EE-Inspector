/**
 * Every data shape in the project, in one place (ADR-0006, docs/plans/2026-11-14-central-schemas.md).
 *
 * The game writes each line as `<PREFIX>\t<json>`: the public record (A7XDATA), the lines of the
 * three checks (A7XCHECK, A7XLIST, A7XSPAWN) and the effect probe's (A7XEFF). Each is defined here once, as a Zod schema; every type
 * is inferred from a schema, never written by hand beside it, so a type and its schema cannot drift.
 * The Lua that writes each prefix is tied to its schema by a golden file in test/fixtures/, which
 * both the Lua test and test/model/schemas_test.ts check. The run types the verify modules build
 * from the lines are at the end, composed from the inferred types.
 *
 * Objects are strict: a field the schema does not name fails, as a missing or mistyped one does.
 * The Lua encoder leaves out a value it could not read, so a field is optional only where "not read"
 * is itself a result to report.
 */
import { z } from "jsr:@zod/zod@4";

// Shared pieces.

const int = z.number().int();
const SIDES = ["party", "ally", "neutral", "enemy"] as const;
const GROUPS = ["friendly", "neutral", "hostile"] as const;
export const SAVES = ["death", "wand", "poly", "breath", "spell"] as const;
export const RESISTS = [
  "fire",
  "cold",
  "electricity",
  "acid",
  "magic_fire",
  "magic_cold",
  "slashing",
  "crushing",
  "piercing",
  "missile",
] as const;
const AC_MODS = ["crushing", "missile", "piercing", "slashing"] as const;

/** An object with these integer fields, all required, nothing else. */
const integers = <K extends string>(keys: readonly K[]) =>
  z.strictObject(Object.fromEntries(keys.map((k) => [k, int])) as { [P in K]: typeof int });

const Hp = z.strictObject({ cur: int, max: int });

// The public record: A7XDATA, schema 1 (docs/data-model.md, docs/api.md). Its JSON Schema, for tools
// that do not use TypeScript, is generated by `deno task schema` into docs/data-model.schema.json.

export const RecordSchema = z.strictObject({
  schema: z.literal(1).describe("the record format's version"),
  id: int.describe("the engine's id for the creature, valid for this game session"),
  resref: z.string().max(8).describe("the name of the .cre file the creature was made from"),
  name: z.string().describe("the name the game shows for it"),
  allegiance: z.strictObject({
    ea: int.min(0).max(255).describe("the engine's allegiance value (IESDP's EA.IDS)"),
    side: z.enum(SIDES).describe("ea in words; party for a party member"),
  }).describe("whose side the creature is on"),
  hp: Hp.describe("hit points now, and the maximum"),
  ac: int.describe("armor class"),
  ac_mods: integers(AC_MODS).describe("AC adjustments against each kind of attack"),
  thac0: int.describe("THAC0, before the bonuses of the weapon in hand"),
  saves: integers(SAVES).describe("saving throws"),
  resist: integers(RESISTS).describe("resistances, in percent"),
  mr: int.describe("magic resistance, in percent"),
}).describe("A creature as the inspector reads it, schema 1");

export type CreatureRecord = z.infer<typeof RecordSchema>;

/** The record's JSON Schema, for docs/data-model.schema.json. */
export function recordJsonSchema(): unknown {
  return z.toJSONSchema(RecordSchema);
}

// The party check: A7XCHECK (test/lua/a7xchk.lua, docs/manual-tests/walker.md). The walker's value
// and the record screen's for each field; evidence lines (walk, dump) about each member.

/** A compared value: text or a number; left out when it could not be read. */
const Value = z.union([z.string(), z.number()]).optional();

export const CheckLine = z.discriminatedUnion("kind", [
  z.strictObject({ run: int, kind: z.literal("party"), size: int }),
  z.strictObject({
    run: int,
    kind: z.literal("field"),
    id: int,
    field: z.string(),
    walker: Value,
    engine: Value,
    ok: z.boolean(),
  }),
  z.strictObject({ run: int, kind: z.literal("skip"), id: int, why: z.string() }),
  z.strictObject({
    run: int,
    kind: z.literal("walk"),
    id: int,
    block: z.string(),
    state: int.optional(),
    thac0_stat: int.optional(),
    mr: int.optional(),
    resist: integers(RESISTS).partial(),
    keys: z.array(z.string()),
    proficiencies_keys: z.array(z.string()),
    saving_throws: z.string().optional(),
  }),
  // 512 bytes of a member's sprite from offset `at`, one line per chunk: the game's log cuts a message
  // after 4084 characters, so a whole dump in one line would be cut.
  z.strictObject({ run: int, kind: z.literal("dump"), id: int, at: int, hex: z.string() }),
  z.strictObject({ run: int, kind: z.literal("error"), why: z.string() }),
]);

export type CheckLine = z.infer<typeof CheckLine>;

