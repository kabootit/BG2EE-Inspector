export type EffectLine = z.infer<typeof EffectLine>;

/** One kind of line of a union, by its `kind`. */
export type Kind<L extends { kind: string }, K extends L["kind"]> = Extract<L, { kind: K }>;

/**
 * The default of a `switch` over every kind of a line: TypeScript refuses to compile it while a
 * kind is unhandled, so a kind added to a schema cannot be silently ignored by the code that judges it.
 */
export function exhaustive(line: never): never {
  throw new Error(`unhandled line: ${JSON.stringify(line)}`);
}

// Reading lines from a session log.

export type Parsed<T> = { lines: T[]; count: number; problems: string[] };

/**
 * Every `<prefix>\t<json>` line in a log, anywhere in the engine's own log line (`… INFO: LUA:
 * A7XCHECK\t{…}`), parsed and checked against `schema`: the lines that pass, how many were found,
 * and a problem for each that does not, naming its log line.
 */
export function parseLines<T>(log: string, prefix: string, schema: z.ZodType<T>): Parsed<T> {
  // Anything from the first brace on is the JSON: a line cut short is reported as not JSON, never skipped.
  const pattern = new RegExp(`${prefix}\\s+(\\{.*)$`);
  const out: Parsed<T> = { lines: [], count: 0, problems: [] };
  log.split("\n").forEach((raw, i) => {
    const m = raw.trimEnd().match(pattern);
    if (!m) return;
    out.count++;
    let json: unknown;
    try {
      json = JSON.parse(m[1]);
    } catch {
      out.problems.push(`log line ${i + 1}: not JSON`);
      return;
    }
    const result = schema.safeParse(json);
    if (result.success) out.lines.push(result.data);
    else {
      out.problems.push(
        ...result.error.issues.map((issue) =>
          `log line ${i + 1}: ${issue.path.join(".") || "(line)"}: ${issue.message}`
        ),
      );
    }
  });
  return out;
}

/** The record, or why it is not one: each problem as "<path>: <message>". */
export function parseRecord(json: unknown): { record: CreatureRecord } | { problems: string[] } {
  const result = RecordSchema.safeParse(json);
  if (result.success) return { record: result.data };
  return {
    problems: result.error.issues.map((i) => `${i.path.join(".") || "(record)"}: ${i.message}`),
  };
}

// The runs the verify modules build from the lines, composed from the inferred types.

/** A party member in a run of the party check: its compared fields and its evidence. */
export type CheckMember = {
  id: number;
  fields: Kind<CheckLine, "field">[];
  skip?: string;
  walk?: Kind<CheckLine, "walk">;
  dumps: Kind<CheckLine, "dump">[];
};
export type CheckRun = { run: number; size?: number; error?: string; members: CheckMember[] };

export type ListRun = {
  run: number;
  area?: Kind<ListLine, "area">;
  scan?: Kind<ListLine, "scan">;
  creatures: Kind<ListLine, "creature">[];
  checks: Kind<ListLine, "check">[];
  error?: string;
};

export type SpawnCreature = Kind<SpawnLine, "creature">;
export type SpawnRun = {
  run: number;
  spawned: Kind<SpawnLine, "spawn">[];
  creatures: SpawnCreature[];
  headers: Map<number, Uint8Array | null>;
  error?: string;
};

/** A party member in a run of the effect probe: its lists, their effects, and the engine's icons. */
export type EffectMember = {
  id: number;
  lists: Kind<EffectLine, "list">[];
  effects: Kind<EffectLine, "effect">[];
  status?: Kind<EffectLine, "status">;
  skip?: string;
};
export type EffectRun = {
  run: number;
  size?: number;
  ticks?: number;
  members: EffectMember[];
  error?: string;
};

/** One field of a spawned creature: the walker's value against its .cre file's. */
export type Comparison = { field: string; walker: number; file: number; ok: boolean };
